export function detectBrowserLanguage(): LanguageCode {
  if (typeof window === 'undefined' || !window.navigator) return 'es';
  
  const langs = (navigator.languages && navigator.languages.length > 0)
    ? Array.from(navigator.languages)
    : [navigator.language || (navigator as any).userLanguage || 'es'];

  for (const rawLang of langs) {
    const raw = (rawLang || '').toLowerCase();
    if (raw.startsWith('es')) return 'es';
    if (raw.startsWith('en')) return 'en';
    if (raw.startsWith('de')) return 'de';
    if (raw.startsWith('fr')) return 'fr';
    if (raw.startsWith('it')) return 'it';
    if (raw.startsWith('ru')) return 'ru';
    if (raw.startsWith('zh')) return 'zh';
    if (raw.startsWith('ja')) return 'ja';
    if (raw.startsWith('pt')) return 'pt';
  }
  return 'es'; // Default to Spanish for Spanish users
}

export function getTranslation(lang: LanguageCode): TranslationDict {
  return translations[lang] || translations.en;
}
